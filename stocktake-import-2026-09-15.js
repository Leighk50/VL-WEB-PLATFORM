function norm(v){return String(v||"").toLowerCase().replace(/[^a-z0-9]+/g," ").trim();}
function key(desc,size){return `${norm(desc)}|${norm(size)}`;}
function load(){try{return JSON.parse(fs.readFileSync(FILE,"utf8"));}catch{return {version:1,updatedAt:null,items:[],counts:{},accessUsers:[],imports:[]};}}
function save(data){fs.mkdirSync(DATA_DIR,{recursive:true});const tmp=FILE+".import.tmp";fs.writeFileSync(tmp,JSON.stringify(data,null,2),{encoding:"utf8",mode:0o600});fs.renameSync(tmp,FILE);try{fs.chmodSync(FILE,0o600);}catch{}}

const data=load();
data.items=Array.isArray(data.items)?data.items:[];data.counts=data.counts&&typeof data.counts==="object"?data.counts:{};data.accessUsers=Array.isArray(data.accessUsers)?data.accessUsers:[];data.imports=Array.isArray(data.imports)?data.imports:[];
if(data.imports.includes(SEED)){process.exit(0);}
const now=new Date().toISOString();
for(const [type,description,size,location,quantity] of rows){
  let item=data.items.find(i=>key(i.description,i.size)===key(description,size));
  if(!item){item={id:crypto.randomUUID(),type,description,size,costPrice:null,createdAt:now,updatedAt:now};data.items.push(item);}else{if(!item.type)item.type=type;if(item.costPrice===undefined)item.costPrice=null;item.updatedAt=now;}
  data.counts[item.id]=data.counts[item.id]||{bar:0,cellar:0,walk_in_fridge:0};
  data.counts[item.id][location]=Number(quantity)||0;
}
data.updatedAt=now;data.imports.push(SEED);save(data);
console.log(`Imported ${rows.length} handwritten stock rows into ${data.items.length} master products.`);
